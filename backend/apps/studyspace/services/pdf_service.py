MAX_TOC_INDENT_LEVEL = 4


class BlockAnchors:
    """Assigns an id to every block a reader can point at.

    The id is derived from the block's own text rather than its position, so
    re-converting the same source yields the same anchors and a highlight saved
    months ago still resolves. Position-based ids would shift the moment the
    extraction pipeline classified one block differently.

    Blocks whose text is genuinely identical are disambiguated by order of
    appearance, which is the one case where an anchor can still move: inserting
    a duplicate ahead of an existing one renumbers the ones that follow.
    """

    def __init__(self):
        self._occurrences = Counter()
        self.page_number = 0

    def assign(self, element):
        text = " ".join("".join(element.itertext()).split())
        if not text:
            return None

        digest = hashlib.sha1(text.encode("utf-8")).hexdigest()[:ANCHOR_DIGEST_LENGTH]
        self._occurrences[digest] += 1
        occurrence = self._occurrences[digest]

        # The prefix keeps the id from starting with a digit, which would need
        # escaping every time it was used as a CSS selector.
        if occurrence == 1:
            return f"{ANCHOR_PREFIX}{digest}"
        return f"{ANCHOR_PREFIX}{digest}-{occurrence}"


class _AnchorTreeprocessor(Treeprocessor):
    def __init__(self, md, anchors):
        super().__init__(md)
        self.anchors = anchors

    def run(self, root):
        for element in root.iter():
            if element.tag not in ANCHORED_TAGS:
                continue

            anchor = self.anchors.assign(element)
            if anchor is None:
                continue

            element.set("id", anchor)
            element.set("data-pagina", str(self.anchors.page_number))


class AnchorExtension(Extension):
    """Adds stable ids to block elements as Markdown is rendered."""

    def __init__(self, anchors):
        super().__init__()
        self.anchors = anchors

    def extendMarkdown(self, md):
        # After inline processing (20) so the text is final, before prettify
        # (10) so no cosmetic whitespace has been introduced yet.
        md.treeprocessors.register(
            _AnchorTreeprocessor(md, self.anchors), "studyspace_anchors", 15
        )


def _render_toc(toc_entries):
    """Build a navigable index from the PDF's embedded outline.

    Entries arrive as [level, title, page]. Anchors point at the page div,
    which is the finest granularity the outline actually guarantees.
    """
    if not toc_entries:
        return ""

    parts = ['<div class="pagina">\n', "<h1>Índice</h1>\n", '<ul class="indice">\n']

    for level, entry_title, page_number in toc_entries:
        indent = min(max(level, 1), MAX_TOC_INDENT_LEVEL)
        parts.append(
            f'    <li class="nivel-{indent}">'
            f'<a href="#pagina-{page_number}">{html.escape(entry_title)}</a>'
            f'<span class="puntos" aria-hidden="true"></span>'
            f'<span class="pagina-ref">{page_number}</span></li>\n'
        )

    parts.append("</ul>\n</div>\n")
    return "".join(parts)


def pdf_to_html(pdf_bytes, title="Libro Convertido"):
    """Convert PDF bytes into a standalone HTML document, one div per page.

    Extraction goes through pymupdf4llm, which detects multi-column layouts and
    tables before serialising to Markdown. That Markdown is then rendered to
    semantic HTML carrying no inline styles, so the stylesheet above owns
    typography and colors outright.

    The bytes are staged on disk on purpose. Handing pymupdf4llm a Document
    opened from a stream makes it carry state over from the previously
    converted document — images from the earlier file reappear and heading
    detection collapses. Converting from a path is unaffected, and in a
    long-lived worker process that difference is the gap between isolated
    requests and one upload bleeding into the next.
    """
    # Reading the outline from the stream both validates the upload and keeps a
    # malformed file from ever reaching disk. This Document is never handed to
    # pymupdf4llm, so the state carry-over described above does not apply.
    with fitz.open(stream=pdf_bytes, filetype="pdf") as document:
        toc_entries = document.get_toc()

    descriptor, pdf_path = tempfile.mkstemp(suffix=".pdf")
    try:
        with os.fdopen(descriptor, "wb") as staged_pdf:
            staged_pdf.write(pdf_bytes)

        pages = pymupdf4llm.to_markdown(
            pdf_path,
            page_chunks=True,
            embed_images=True,
        )
    finally:
        # Never let cleanup mask a conversion error.
        try:
            os.unlink(pdf_path)
        except OSError:
            pass

    parts = [DOCUMENT_HEAD.replace("{title}", html.escape(title), 1)]
    parts.append(_render_toc(toc_entries))

    # One renderer for the whole document so the anchor registry can keep
    # duplicate block text unique across pages, not just within a page.
    anchors = BlockAnchors()
    renderer = markdown.Markdown(
        extensions=[*MARKDOWN_EXTENSIONS, AnchorExtension(anchors)]
    )

    for page_number, page in enumerate(pages, start=1):
        anchors.page_number = page_number

        parts.append(f'\n<div class="pagina" id="pagina-{page_number}">\n')
        parts.append(f'    <div class="numero-pagina">Página {page_number}</div>\n')
        parts.append(renderer.reset().convert(page["text"]))
        parts.append("\n</div>\n")

    parts.append(DOCUMENT_TAIL)
    return "".join(parts)
